import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = await mkdtemp(join(tmpdir(), 'famie-coverage-mapping-'))
try {
  const destination = join(directory, 'lcov.info')
  const run = spawnSync(process.execPath, [
    '--experimental-transform-types', '--enable-source-maps', '--experimental-test-coverage',
    '--test-coverage-include=fixtures/mapping.ts', '--test', '--test-reporter=lcov',
    `--test-reporter-destination=${destination}`, 'fixtures/mapping-test.mjs',
  ], { cwd: fileURLToPath(new URL('./', import.meta.url)), encoding: 'utf8', timeout: 30_000 })
  assert.equal(run.status, 0, run.stderr)
  const report = await readFile(destination, 'utf8')
  // Original TypeScript line numbers, including parameter properties transformed by Node.
  assert.match(report, /^DA:3,0$/m, 'Uncalled constructor body must remain uncovered')
  assert.match(report, /^DA:8,[1-9]\d*$/m, 'Executed branch must map to the original source')
  assert.match(report, /^BRDA:8,\d+,\d+,0$/m, 'Unexecuted branch must remain in the denominator at its original if line')
  assert.match(report, /^FNH:1$/m, 'Class constructor must not be counted as executed')
  console.log('TypeScript coverage mapping and unexecuted denominator: passed')
} finally {
  // Only the directory generated by this test, containing its non-sensitive LCOV file.
  await rm(directory, { recursive: true, force: true })
}
